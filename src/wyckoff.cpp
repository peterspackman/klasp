// Fractional difference reduced to (-0.5, 0.5].
inline double wrap_delta(double d) { return d - std::round(d); }

inline void apply_op(const SymopData& op, const double x[3], double out[3]) {
    for (int i = 0; i < 3; ++i) {
        out[i] = op.trans[i];
        for (int j = 0; j < 3; ++j) out[i] += op.rot[i][j] * x[j];
    }
}

inline bool same_site(const double a[3], const double b[3], double tol) {
    for (int i = 0; i < 3; ++i)
        if (std::abs(wrap_delta(a[i] - b[i])) > tol) return false;
    return true;
}

