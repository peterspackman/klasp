std::vector<double> orientations_on_site(const std::vector<double>& site_ops_cart,
                                         const std::vector<double>& mol_ops,
                                         int* degrees_of_freedom, double tol) {
    const size_t nw = site_ops_cart.size() / 9, nm = mol_ops.size() / 9;
    std::vector<double> out;
    if (degrees_of_freedom) *degrees_of_freedom = 2;
    if (nw <= 1) {                       // a general position constrains nothing
        const double I[9] = {1,0,0, 0,1,0, 0,0,1};
        out.assign(I, I + 9);
        return out;
    }
    // A molecule cannot supply more symmetry than it has.
    if (nm < nw) { if (degrees_of_freedom) *degrees_of_freedom = 0; return out; }

    // Constraint axes from the site: the first with an axis, then the first not
    // parallel to it. Two independent axes pin a frame; one leaves a turn about
    // it, which is what makes degrees_of_freedom 1 rather than 0.
    double w1[3], w2[3];
    bool have1 = false, have2 = false;
    for (size_t i = 0; i < nw && !have2; ++i) {
        double a[3];
        if (!op_axis(&site_ops_cart[i*9], a)) continue;
        if (!have1) { for (int k=0;k<3;++k) w1[k]=a[k]; have1 = true; continue; }
        const double d = std::abs(w1[0]*a[0] + w1[1]*a[1] + w1[2]*a[2]);
        if (d < 1 - 1e-3) { for (int k=0;k<3;++k) w2[k]=a[k]; have2 = true; }
    }

    auto accept = [&](const double* R) {
        // Every site operation must be one the molecule already has, once the
        // molecule is turned by R: R^-1 W R in M.
        double Rt[9]; mat_t(R, Rt);
        for (size_t i = 0; i < nw; ++i) {
            double tmp[9], conj[9];
            mat_mul(Rt, &site_ops_cart[i*9], tmp);
            mat_mul(tmp, R, conj);
            if (!contains_op(mol_ops, conj, tol)) return false;
        }
        if (!contains_op(out, R, 1e-6)) out.insert(out.end(), R, R + 9);
        return true;
    };

    if (!have1) {                        // inversion only: any orientation works
        const double I[9] = {1,0,0, 0,1,0, 0,0,1};
        if (accept(I) && degrees_of_freedom) *degrees_of_freedom = 2;
        return out;
    }

    // Candidate molecular axes to align the site's onto, both senses.
    std::vector<std::array<double,3>> mol_axes;
    for (size_t i = 0; i < nm; ++i) {
        double a[3];
        if (!op_axis(&mol_ops[i*9], a)) continue;
        mol_axes.push_back({a[0], a[1], a[2]});
        mol_axes.push_back({-a[0], -a[1], -a[2]});
    }
    if (mol_axes.empty()) { if (degrees_of_freedom) *degrees_of_freedom = 0; return out; }

    if (!have2) {
        // One constraint. Align the site axis to each molecular axis and take an
        // arbitrary perpendicular for the second frame vector; a turn about the
        // axis survives, so report one degree of freedom.
        for (const auto& m : mol_axes) {
            double perp[3] = {0, 0, 1};
            if (std::abs(m[2]) > 0.9) { perp[0] = 1; perp[2] = 0; }
            double wperp[3] = {0, 0, 1};
            if (std::abs(w1[2]) > 0.9) { wperp[0] = 1; wperp[2] = 0; }
            double R[9];
            frame_rotation(m.data(), perp, w1, wperp, R);
            accept(R);
        }
        if (degrees_of_freedom) *degrees_of_freedom = out.empty() ? 0 : 1;
        return out;
    }

    // Two constraints: the frame is pinned, so try every ordered pair of
    // molecular axes whose angle matches the site's.
    const double want = w1[0]*w2[0] + w1[1]*w2[1] + w1[2]*w2[2];
    for (const auto& m1 : mol_axes)
        for (const auto& m2 : mol_axes) {
            const double d = m1[0]*m2[0] + m1[1]*m2[1] + m1[2]*m2[2];
            if (std::abs(d - want) > 1e-3) continue;
            if (std::abs(d) > 1 - 1e-3) continue;      // parallel: no frame
            double R[9];
            frame_rotation(m1.data(), m2.data(), w1, w2, R);
            accept(R);
        }
    if (degrees_of_freedom) *degrees_of_freedom = out.empty() ? 0 : 0;
    return out;
}


WyckoffReport wyckoff_report(int space_group, const std::vector<double>& mol_ops) {
    const SpaceGroupInfo& sg = get_space_group(space_group);
    WyckoffReport rep;
    rep.space_group = space_group;
    rep.n_symops = sg.n_symops;
    rep.mol_n_ops = static_cast<int>(mol_ops.size() / 9);

    double cell[3][3];
    canonical_cell(sg.lattice, cell);
    for (const auto& s : special_positions(sg)) {
        WyckoffReport::Entry e;
        e.site_order = s.site_order;
        e.multiplicity = s.multiplicity;
        e.n_free = s.n_free;
        for (int i = 0; i < 3; ++i) e.rep[i] = s.rep[i];
        const auto w = site_ops_cartesian(sg, s, cell);
        int dof = 0;
        const auto oris = orientations_on_site(w, mol_ops, &dof);
        e.n_orientations = static_cast<int>(oris.size() / 9);
        e.orientation_dof = e.n_orientations ? dof : 0;
        rep.entries.push_back(e);
    }
    return rep;
}

